export interface EmojiGroup {
  key: string;
  icon: string;
  emojis: string[];
}

const EMOJI_GROUP_DEFS: { key: string; icon: string; marker: string }[] = [
  { key: 'chat.emoji.recent', icon: '🙂', marker: '😀' },
  { key: 'chat.emoji.people', icon: '😄', marker: '😃' },
  { key: 'chat.emoji.gestures', icon: '👍', marker: '👋' },
  { key: 'chat.emoji.hearts', icon: '❤️', marker: '🤍' },
  { key: 'chat.emoji.food', icon: '🍔', marker: '🍎' },
  { key: 'chat.emoji.animals', icon: '🐱', marker: '🐭' },
  { key: 'chat.emoji.objects', icon: '💡', marker: '📱' },
  { key: 'chat.emoji.symbols', icon: '✅', marker: '❗' }
];

/** 按特征表情把扁平 EMOJIS 切分为分组（无需重复罗列） */
export function buildEmojiGroups(): EmojiGroup[] {
  return EMOJI_GROUP_DEFS.map((g, i) => {
    const start = EMOJIS.indexOf(g.marker);
    const end = i + 1 < EMOJI_GROUP_DEFS.length ? EMOJIS.indexOf(EMOJI_GROUP_DEFS[i + 1].marker) : EMOJIS.length;
    return { key: g.key, icon: g.icon, emojis: EMOJIS.slice(start, end) };
  });
}

